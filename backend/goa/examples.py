                merchant_id="mer_example",
                product_name="Example Midi Wrap Dress",
                size="M",
                unit_price_cents=129900,
                selected_by=SelectedBy.SYSTEM_SUGGESTION,
                semantic_score=0.82,
                matched_attributes=["colour:green"],
                verification_result=example_verification(),
