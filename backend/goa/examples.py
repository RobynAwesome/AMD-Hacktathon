CANONICAL_PROMPT = (
    "Graduation in Cape Town on 12 December, outdoor, warm. Green, elegant but not formal, "
    "something I can wear again. Budget R2,500."
)

T0 = datetime(2026, 10, 17, 17, 0, tzinfo=timezone.utc)


def _pass(reason: str, **evidence) -> CheckResult:
    return CheckResult(state=CheckState.PASS, reason=reason, evidence=evidence)


def example_verification() -> VerificationResult:
    return VerificationResult(
        exists_in_catalogue=_pass("product and variant found", product_id="prd_example_dress", variant_id="var_example_dress_m"),
        correct_part_type=_pass("part type matches", expected="DRESS_OR_SUIT", actual="DRESS_OR_SUIT"),
        size_available=_pass("size offered", requested_size="M"),
        stock_available=_pass("positive stock", stock_quantity=4),
        delivery_feasible=_pass("arrives before event", lead_days=5, arrival_date="2026-10-22", event_date="2026-12-12"),
        price_known=_pass("valid ZAR integer cents", price_cents=129900, currency="ZAR"),
        budget_feasible=_pass("item within budget", price_cents=129900, budget_cents=250000),
        overall=CheckState.PASS,
        engine_version="goa-verify-1.0.0",
        evaluated_on=date(2026, 10, 17),
    )


def example_merchant() -> Merchant:
    return Merchant(
        merchant_id="mer_example",
        name="Example Atelier (fictional)",
        description="A fictional demo merchant.",
        is_fictional=True,
        location="Cape Town (fictional business)",
        catalogue_status=CatalogueStatus.ACTIVE,
        created_at=T0,
    )


def example_product() -> Product:
    return Product(
        product_id="prd_example_dress",
        merchant_id="mer_example",
        name="Example Midi Wrap Dress",
        description="Synthetic demo product.",
        part_type=PartType.DRESS_OR_SUIT,
        colour="emerald green",
        material="linen",
        style_tags=["midi", "wrap", "breathable"],
        formality=Formality.SMART_CASUAL,
        image_url="/catalogue/prd_example_dress.svg",
        image_licence="CC0-1.0",
        image_attribution="Original illustration generated by GOA seed script.",
        price_cents=129900,
        currency="ZAR",
        delivery_lead_days=5,
        active=True,
        source_type=ProductSourceType.SYNTHETIC_DEMO,
        variants=[ProductVariant(variant_id="var_example_dress_m", size="M", stock_quantity=4)],
    )


def example_requested_part() -> RequestedPart:
    return RequestedPart(
        part_id="prt_example_dress",
        brief_id="brf_example",
        part_type=PartType.DRESS_OR_SUIT,
        origin=PartOrigin.INFERRED_DEFAULT,
        desired_attributes=DesiredAttributes(colours=["green"], style_tags=["elegant", "breathable"], formality=Formality.SMART_CASUAL),
        mandatory_constraints=MandatoryConstraints(size="M", must_arrive_by=date(2026, 12, 11)),
        optional_preferences=["rewearable"],
        status=PartStatus.AVAILABLE,
    )


def example_brief() -> CreativeBrief:
    return CreativeBrief(
        brief_id="brf_example",
        session_id="ses_example",
        raw_prompt=CANONICAL_PROMPT,
        occasion="graduation",
        event_date=date(2026, 12, 12),
        location="Cape Town",
        budget_cents=250000,
        preferred_colours=["green"],
        formality=Formality.SMART_CASUAL,
        style_preferences=["elegant", "outdoor", "warm-weather", "breathable"],
        sustainability_or_reuse_preferences=["rewearable"],
        sizes={PartType.DRESS_OR_SUIT: "M"},
        constraints=["outdoor event", "warm weather"],
        requested_parts=[example_requested_part()],
        uncertainties=["event year inferred as next occurrence (2026)", "shoe size not supplied"],
        interpretation_source=InterpretationSource.RULE_BASED_FALLBACK,
        created_at=T0,
    )


