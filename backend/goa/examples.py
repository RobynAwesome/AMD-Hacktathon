def example_receipt() -> ValidationReceipt:
    receipt = ValidationReceipt(
        revalidated_at=T0,
        engine_version="goa-verify-1.0.0",
        evaluated_on=date(2026, 10, 17),
        event_date=date(2026, 12, 12),
        budget_cents=250000,
        items=[
            ItemRevalidation(
                part_id="prt_example_dress",
                product_id="prd_example_dress",
                variant_id="var_example_dress_m",
                merchant_id="mer_example",
                belongs_to_addressed_merchant=True,
                verified_unit_price_cents=129900,
                verified_stock_quantity=4,
                verification_result=example_verification(),
            )
        ],
        all_items_pass=True,
    )
    receipt.receipt_digest = receipt.compute_digest()
    return receipt


