def _slug(name: str) -> str:
    return "".join(c if c.isalnum() else "_" for c in name.lower()).strip("_").replace("__", "_")[:40]


def _svg(part_type: str, tags: list[str], colour: str, name: str) -> str:
    fill = HEX.get(colour, "#888888")
    stroke = "#2b2b2b"
    if part_type == D and ("suit" in tags or "jumpsuit" in tags):
        shape = ('<path d="M70 40 L100 30 L130 40 L150 95 L135 100 L130 75 L128 210 L104 210 L100 120 L96 210 L72 210 '
                 'L70 75 L65 100 L50 95 Z"/>')
    elif part_type == D:
        shape = '<path d="M85 30 L115 30 L120 70 L150 210 L50 210 L80 70 Z"/><path d="M85 30 L100 48 L115 30" fill="none"/>'
    elif part_type == S:
        shape = '<path d="M40 150 Q45 120 80 125 L120 140 Q160 145 165 165 L165 175 L40 175 Z"/><rect x="45" y="175" width="25" height="18"/>'
    elif part_type == O:
        shape = ('<path d="M65 40 L100 55 L135 40 L160 80 L150 205 L108 205 L100 70 L92 205 L50 205 L40 80 Z"/>')
    else:
        if "earrings" in tags or "cufflinks" in tags or "necklace" in tags:
            shape = '<circle cx="75" cy="110" r="22"/><circle cx="125" cy="110" r="22"/>'
        elif "hat" in tags:
            shape = '<ellipse cx="100" cy="140" rx="75" ry="20"/><path d="M60 140 Q65 85 100 85 Q135 85 140 140 Z"/>'
        else:
            shape = '<rect x="50" y="90" width="100" height="80" rx="12"/><path d="M75 90 Q100 50 125 90" fill="none"/>'
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 200 240" role="img" aria-label="{name}">'
        f'<rect width="200" height="240" fill="#f6f2ea"/>'
        f'<g fill="{fill}" stroke="{stroke}" stroke-width="2" stroke-linejoin="round">{shape}</g>'
        f'<text x="100" y="232" font-family="sans-serif" font-size="9" text-anchor="middle" fill="#6b6357">'
        f'GOA demo illustration</text></svg>\n'
    )


def build() -> tuple[list[dict], list[dict], dict[str, str]]:
    rng = random.Random(20261018)
    merchants = [
        Merchant(merchant_id=m, name=f"{n} (fictional demo merchant)", description=d, is_fictional=True,
                 location=loc, catalogue_status="ACTIVE", created_at=CREATED).model_dump(mode="json")
        for m, n, d, loc in MERCHANTS
    ]
    products, svgs, seen = [], {}, set()
    for merchant_id, part_type, name, colour, material, tags, formality, price_rand, lead in ITEMS:
        pid = f"prd_{_slug(name)}"
        assert pid not in seen, pid
        seen.add(pid)
        sizes = APPAREL_SIZES if part_type in (D, O) else SHOE_SIZES if part_type == S else ["ONE_SIZE"]
        variants = [
            {"variant_id": f"var_{pid[4:]}_{s.lower()}", "size": s, "stock_quantity": rng.choice([0, 1, 2, 3, 4, 5, 6])}
            for s in sizes
        ]
        product = Product(
            product_id=pid, merchant_id=merchant_id, name=name,
            description=f"Synthetic demo product: {colour} {material} {', '.join(tags[:3])}.",
            part_type=part_type, colour=colour, material=material, style_tags=tags, formality=formality,
            image_url=f"/catalogue/{pid}.svg", image_licence=LICENCE, image_attribution=ATTRIBUTION,
            price_cents=None if price_rand is None else price_rand * 100, currency="ZAR",
            delivery_lead_days=lead, active=True, source_type="SYNTHETIC_DEMO", variants=variants,
        )
        products.append(product.model_dump(mode="json"))
        svgs[pid] = _svg(part_type, tags, colour, name)
    return merchants, products, svgs


def main() -> None:
    merchants, products, svgs = build()
    data = ROOT / "data"
    data.mkdir(exist_ok=True)
    (data / "merchants.json").write_text(json.dumps(merchants, indent=2) + "\n", encoding="utf-8", newline="\n")
    (data / "products.json").write_text(json.dumps(products, indent=2) + "\n", encoding="utf-8", newline="\n")
    img = ROOT / "frontend" / "catalogue"
    img.mkdir(parents=True, exist_ok=True)
    for pid, svg in svgs.items():
        (img / f"{pid}.svg").write_text(svg, encoding="utf-8", newline="\n")
    print(f"{len(merchants)} merchants, {len(products)} products, {len(svgs)} illustrations")


if __name__ == "__main__":
    main()
